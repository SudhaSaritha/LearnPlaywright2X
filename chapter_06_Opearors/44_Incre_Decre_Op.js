// Pre Increment
let a = 10;
let R1 = ++a; // increment a by 1


// Pre increment -> ++a -> increase the value and then assign.
console.log(R1);
console.log(a);

let b = 10;
let R2 = ++b; // increment b by 1


// Pre increment -> ++b -> increase the value and then assign.
console.log(R2);
console.log(b);

//Derement
// Pre Decrement
let c = 10;
let D1 = --c; // increment a by 1


// Pre Decrement -> --c -> decrease the value and then assign.
console.log(D1);
console.log(c);

// Pre Decrement
let D = 10;
let D2 = --c; // increment a by 1


// Pre Decrement -> --a -> decrease the value and then assign.
