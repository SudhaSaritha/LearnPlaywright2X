let day = 10;
//1-mon, 2-Tue, 3-Wed
switch (day) {
    case 0:
        console.log("Mon");
        break;
    case 1:
        console.log("Tue");
        break;
    case 2:
        console.log("wed");
        break;
    case 3:
        console.log("Thurs");
        break;
    case 4:
        console.log("fri");
        break;
    case 5:
        console.log("sat");
        break;
    case 6:
        console.log("sun");
        break;
    default:
        console.log("no day matched");
        break;
}